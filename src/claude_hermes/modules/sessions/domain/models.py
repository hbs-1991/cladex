"""Conversation state: the SDK session per lane, the recall corpus, and the
thread metadata that must outlive a session reset."""
from __future__ import annotations

import sqlalchemy as sa
from sqlalchemy import (
    BigInteger,
    Boolean,
    Computed,
    Float,
    ForeignKey,
    Index,
    Integer,
    Text,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from claude_hermes.core.db.base import Base

# Wave 4a: every user-owned row names its owner. The FK is spelled by table name,
# never by importing identity's model — modules are independent of each other, and
# `Base.metadata` is where the two tables actually meet.
#
# `ON DELETE SET NULL` and nullable: deleting a user must not delete their history,
# and an old row from before 0005 has to survive. Code always writes a non-NULL
# owner, and a NULL row is visible to nobody (D2). A function, not a constant: a
# `ForeignKey` object binds to exactly one column.
def _owner_fk() -> ForeignKey:
    return ForeignKey("users.id", ondelete="SET NULL")


class Session(Base):
    __tablename__ = "sessions"
    session_key: Mapped[str] = mapped_column(Text, primary_key=True)
    sdk_session_id: Mapped[str | None] = mapped_column(Text)
    system_append: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[str] = mapped_column(Text, nullable=False)
    updated_at: Mapped[str] = mapped_column(Text, nullable=False)
    # The wiki index mtime this lane has already been shown. It was a dict on the
    # turn service — fine while one process served every lane, a cache-hit-rate
    # regression the moment N workers each hold their own copy and re-inject an
    # 8000-character index the lane has already seen. NULL means "never shown",
    # which is what a missing dict key meant.
    index_mtime: Mapped[float | None] = mapped_column(Float)
    # The lane's owner — `lane_owner(session_key, channel, user_id, deploy_owner)`
    # (D3), written by whoever binds the lane. The workspace resolver applies the
    # same rule to the key, so the two cannot disagree about a lane.
    owner_id: Mapped[int | None] = mapped_column(BigInteger, _owner_fk())
    # What actually RAN this session (0008), as catalog ids. A changed personal
    # default waits for the next session because a live one's cached prefix is
    # model-scoped (P1); the resolver reads this to know what "live" is on. NULL on
    # a session that began before 0008, which ran the deploy default.
    model: Mapped[str | None] = mapped_column(Text)
    effort: Mapped[str | None] = mapped_column(Text)
    # Whether this session was started WITH a shell (0009) — the lane's `has_shell`
    # when it was bound. The toolset is part of the cached prefix (P1), so the turn
    # compares this with the lane's current grant and starts a fresh session when
    # they differ. NULL on a session that began before 0009, which ran under the
    # old rule (`is_owner_lane or users_shell_enabled`); the turn compares it with
    # that rule instead.
    shell_enabled: Mapped[bool | None] = mapped_column(Boolean)
    __table_args__ = (Index("ix_sessions_owner", "owner_id"),)


class Message(Base):
    """Cross-session recall. `content_tsv` is generated by PostgreSQL; the GIN
    index is what makes `search_messages` a full-text query, not a scan."""
    __tablename__ = "messages"
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    session_key: Mapped[str] = mapped_column(Text, nullable=False)
    role: Mapped[str] = mapped_column(Text, nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    ts: Mapped[str] = mapped_column(Text, nullable=False)
    # Denormalised on purpose (D2.5): search is one GIN query and has to stay one
    # query — `WHERE owner_id = :uid AND content_tsv @@ …`. Joining `sessions` to
    # find the owner would put a second table in front of the index.
    owner_id: Mapped[int | None] = mapped_column(BigInteger, _owner_fk())
    content_tsv = mapped_column(
        TSVECTOR, Computed(
            "to_tsvector('simple', regexp_replace(content, '[^[:alnum:]]+', ' ', 'g'))",
            persisted=True))
    __table_args__ = (
        Index("ix_messages_session_key_ts", "session_key", "ts"),
        Index("ix_messages_content_tsv", "content_tsv", postgresql_using="gin"),
        Index("ix_messages_owner_ts", "owner_id", "ts"),
    )


class Thread(Base):
    __tablename__ = "threads"
    session_key: Mapped[str] = mapped_column(Text, primary_key=True)
    title: Mapped[str | None] = mapped_column(Text)
    title_manual: Mapped[int] = mapped_column(Integer, nullable=False, server_default="0")
    channel: Mapped[str] = mapped_column(Text, nullable=False)
    # Wave 4a gives the existing column its FK. Still nullable: `lane_owner` always
    # answers, but a row written before 0005 by a path that had no owner to name
    # must keep resolving rather than fail the constraint.
    owner_user_id: Mapped[int | None] = mapped_column(BigInteger, _owner_fk())
    archived_at: Mapped[str | None] = mapped_column(Text)
    last_event_at: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[str] = mapped_column(Text, nullable=False)
    # Denormalized "somebody has taken a turn in this lane". It was an EXISTS over
    # turn_events, which is the one place the thread list reached into another
    # module's table; the flag buys the module boundary and a cheaper list. Set by
    # the writers that know a turn happened (upsert_thread(..., talked=True)) and
    # never cleared — a lane that was talked in stays talked in.
    has_turns: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=sa.false())
    # The pair the user CHOSE for this lane (0008), as catalog ids; NULL = no
    # explicit choice. On the thread, not the session, so a choice outlives `/new`
    # and every reset a Customize mutation performs.
    model: Mapped[str | None] = mapped_column(Text)
    effort: Mapped[str | None] = mapped_column(Text)
